function t(key, vars) {
  const dict = T[state.language] || T.fr;
  let str = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : (T.fr[key] !== undefined ? T.fr[key] : key);
  if (vars) Object.keys(vars).forEach((k) => { str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]); });
  return str;
}

